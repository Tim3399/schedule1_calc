// Shared rules of team/sync.mjs and `agent-team init`: generator marker, role head fields, config check.
// Runs in the project without the package, so only node: imports (none at all here).

export const MARKER = "generated by team/sync.mjs – do not edit, source: team/roles/";

// File format, not text (T-69): files generated before 0.4.0 carry the German marker line.
// It is read, never written.
export const LEGACY_MARKERS = [
    "generiert von team/sync.mjs – nicht direkt bearbeiten, Quelle: team/roles/",
];
const ALL_MARKERS = [MARKER, ...LEGACY_MARKERS];

// The language rule reaches every role: output styles through _chat-basis.md (section "Language"),
// subagent and Codex files through this block, which sync appends to each of them.
export const LANGUAGE_RULE =
    "Talk to the user in the user's language (German for this user). Everything else (files, commits, messages between agents) is English.";

const toLf = (text) => text.replace(/\r\n/g, "\n");
const isObject = (x) => x !== null && typeof x === "object" && !Array.isArray(x);

// Existing files without a generator marker belong to the project and are never overwritten.
// Codex TOML has the marker in line 1 as "# <MARKER>", Claude Markdown as "<!-- <MARKER> -->"
// in the first line after the front matter (--- … ---). Old and new marker lines both count.
export function hasMarker(rel, text) {
    const lines = toLf(text).split("\n");
    if (rel.endsWith(".toml")) return ALL_MARKERS.some((m) => lines[0] === `# ${m}`);
    if (lines[0] !== "---") return false;
    const end = lines.indexOf("---", 1);
    return end > 0 && ALL_MARKERS.some((m) => lines[end + 1] === `<!-- ${m} -->`);
}

// Head fields of a role file as { key: value }. null without a head.
// Empty lines, comments (#) and lines without ":" are skipped.
export function roleHead(text) {
    const m = toLf(text).match(/^---\n([\s\S]*?)\n---\n/);
    if (!m) return null;
    const head = {};
    for (const line of m[1].split("\n")) {
        const i = line.indexOf(":");
        if (i > 0 && !line.trim().startsWith("#"))
            head[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
    return head;
}

// With "codex" in targets the Codex side needs a complete codex block. Otherwise the TOML would be
// invalid ('undefined', NaN).
export function codexConfigErrors(codex) {
    if (!isObject(codex))
        return ["codex is missing (block with model, effort, reviewModel, webSearch, maxThreads)"];
    const errors = [];
    for (const key of ["model", "effort", "reviewModel", "webSearch"]) {
        if (typeof codex[key] !== "string" || !codex[key].trim())
            errors.push(`codex.${key} is missing, empty or not a string`);
    }
    if (!Number.isInteger(codex.maxThreads) || codex.maxThreads < 1) {
        errors.push(
            `codex.maxThreads must be a positive integer (found: ${JSON.stringify(codex.maxThreads) ?? "nothing"})`,
        );
    }
    return errors;
}

// Project values per role (roles.<role>.codex|claude.<key> in team.config.json).
// Under claude only model and effort are allowed, under codex any key. roleNames: existing roles.
const CLAUDE_ROLE_KEYS = ["model", "effort"];
export function roleOverrideErrors(overrides, roleNames) {
    if (overrides === undefined) return [];
    if (!isObject(overrides))
        return ['roles must be an object { "<role>": { "codex": {…}, "claude": {…} } }'];
    const errors = [];
    for (const [name, entry] of Object.entries(overrides)) {
        if (!roleNames.includes(name)) {
            errors.push(`roles.${name}: unknown role (existing: ${roleNames.join(", ")})`);
            continue;
        }
        if (!isObject(entry)) {
            errors.push(`roles.${name} must be an object`);
            continue;
        }
        for (const [group, values] of Object.entries(entry)) {
            if (!["codex", "claude"].includes(group)) {
                errors.push(`roles.${name}.${group}: only "codex" and "claude" are allowed`);
                continue;
            }
            if (!isObject(values)) {
                errors.push(`roles.${name}.${group} must be an object`);
                continue;
            }
            for (const [key, v] of Object.entries(values)) {
                if (key === "name") errors.push(`roles.${name}.${group}.name cannot be changed`);
                else if (group === "claude" && !CLAUDE_ROLE_KEYS.includes(key))
                    errors.push(
                        `roles.${name}.claude.${key}: only ${CLAUDE_ROLE_KEYS.join(" and ")} are allowed under claude`,
                    );
                else if (typeof v !== "string" || !v.trim() || /[\r\n]/.test(v))
                    errors.push(
                        `roles.${name}.${group}.${key} must be a non-empty single-line string`,
                    );
            }
        }
    }
    return errors;
}

// release block for agent-team set-version (T-46). Without it there is no error (set-version reports that itself).
// verify: commands as argument lists, versionFiles: { path, type: json|toml (key) | regex (pattern, one capture group) }.
const VERSION_FILE_TYPES = ["json", "toml", "regex"];
const isText = (v) => typeof v === "string" && v.trim() !== "";
export function releaseConfigErrors(release) {
    if (release === undefined) return [];
    if (!isObject(release))
        return ["release must be an object { verify, versionFiles, changelog, tagPrefix }"];
    const errors = [];
    const { verify, versionFiles, changelog, tagPrefix } = release;
    if (!Array.isArray(verify) || !verify.length)
        errors.push('release.verify must be a non-empty list of commands, e.g. [["npm", "test"]]');
    else
        verify.forEach((cmd, i) => {
            if (!Array.isArray(cmd) || !cmd.length || !cmd.every((a) => typeof a === "string"))
                errors.push(`release.verify[${i}] must be a non-empty list of strings`);
            else if (!isText(cmd[0])) errors.push(`release.verify[${i}]: command is missing`);
        });
    if (!Array.isArray(versionFiles) || !versionFiles.length)
        errors.push("release.versionFiles must be a non-empty list");
    else
        versionFiles.forEach((f, i) => {
            const at = `release.versionFiles[${i}]`;
            if (!isObject(f)) {
                errors.push(`${at} must be an object { path, type, key | pattern }`);
                return;
            }
            if (!isText(f.path)) errors.push(`${at}.path is missing or empty`);
            if (!VERSION_FILE_TYPES.includes(f.type))
                errors.push(`${at}.type must be ${VERSION_FILE_TYPES.join(", ")}`);
            else if (f.type === "regex") {
                if (!isText(f.pattern)) errors.push(`${at}.pattern is missing or empty`);
                else {
                    let groups = -1;
                    try {
                        groups = new RegExp(`${f.pattern}|`).exec("").length - 1;
                    } catch (e) {
                        errors.push(
                            `${at}.pattern is not a valid regular expression (${e.message})`,
                        );
                    }
                    if (groups >= 0 && groups !== 1)
                        errors.push(
                            `${at}.pattern needs exactly one capture group (found: ${groups})`,
                        );
                }
            } else if (!isText(f.key) || f.key.split(".").some((k) => !k.trim()))
                errors.push(
                    `${at}.key is missing or not a key path (e.g. version, package.version)`,
                );
        });
    if (!isText(changelog))
        errors.push("release.changelog is missing or empty (e.g. CHANGELOG.md)");
    if (typeof tagPrefix !== "string" || /\s/.test(tagPrefix))
        errors.push('release.tagPrefix must be a string without spaces (e.g. "v")');
    return errors;
}

// All config errors that sync reports with exit 2: codex block (only with "codex" in targets), then roles, then release
export function configErrors(config, roleNames) {
    const codex = (config.targets ?? ["claude"]).includes("codex")
        ? codexConfigErrors(config.codex)
        : [];
    return [
        ...codex,
        ...roleOverrideErrors(config.roles, roleNames),
        ...releaseConfigErrors(config.release),
    ];
}
