const toLf = (text) => text.replace(/\r\n/g, "\n");
const isObject = (x) => x !== null && typeof x === "object" && !Array.isArray(x);

// Existing files without a generator marker belong to the project and are never overwritten.
// Codex TOML has the marker in line 1 as "# <MARKER>", Claude Markdown as "<!-- <MARKER> -->"
// in the first line after the front matter (--- … ---). Old and new marker lines both count.
export function hasMarker(rel, text) {
    const lines = toLf(text).split("\n");
    if (rel.endsWith(".toml")) return ALL_MARKERS.some((m) => lines[0] === `# ${m}`);
    if (lines[0] !== "---") return false;
    const end = lines.indexOf("---", 1);
    return end > 0 && ALL_MARKERS.some((m) => lines[end + 1] === `<!-- ${m} -->`);
}

// Head fields of a role file as { key: value }. null without a head.
// Empty lines, comments (#) and lines without ":" are skipped.
export function roleHead(text) {
    const m = toLf(text).match(/^---\n([\s\S]*?)\n---\n/);
    if (!m) return null;
    const head = {};
    for (const line of m[1].split("\n")) {
        const i = line.indexOf(":");
        if (i > 0 && !line.trim().startsWith("#"))
            head[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
    return head;
}

// With "codex" in targets the Codex side needs a complete codex block. Otherwise the TOML would be
// invalid ('undefined', NaN).
export function codexConfigErrors(codex) {
    if (!isObject(codex))
        return ["codex is missing (block with model, effort, reviewModel, webSearch, maxThreads)"];
    const errors = [];
    for (const key of ["model", "effort", "reviewModel", "webSearch"]) {
        if (typeof codex[key] !== "string" || !codex[key].trim())
            errors.push(`codex.${key} is missing, empty or not a string`);
    }
    if (!Number.isInteger(codex.maxThreads) || codex.maxThreads < 1) {
        errors.push(
            `codex.maxThreads must be a positive integer (found: ${JSON.stringify(codex.maxThreads) ?? "nothing"})`,
        );
    }
    return errors;
}

// Project values per role (roles.<role>.codex|claude.<key> in team.config.json).
// Under claude only model and effort are allowed, under codex any key. roleNames: existing roles.
const CLAUDE_ROLE_KEYS = ["model", "effort"];
export function roleOverrideErrors(overrides, roleNames) {
    if (overrides === undefined) return [];
    if (!isObject(overrides))
        return ['roles must be an object { "<role>": { "codex": {…}, "claude": {…} } }'];
    const errors = [];
    for (const [name, entry] of Object.entries(overrides)) {
        if (!roleNames.includes(name)) {
            errors.push(`roles.${name}: unknown role (existing: ${roleNames.join(", ")})`);
            continue;
        }
        if (!isObject(entry)) {
            errors.push(`roles.${name} must be an object`);
            continue;
        }
        for (const [group, values] of Object.entries(entry)) {
            if (!["codex", "claude"].includes(group)) {
                errors.push(`roles.${name}.${group}: only "codex" and "claude" are allowed`);
                continue;
            }
            if (!isObject(values)) {
                errors.push(`roles.${name}.${group} must be an object`);
                continue;
            }
            for (const [key, v] of Object.entries(values)) {
                if (key === "name") errors.push(`roles.${name}.${group}.name cannot be changed`);
                else if (group === "claude" && !CLAUDE_ROLE_KEYS.includes(key))
                    errors.push(
                        `roles.${name}.claude.${key}: only ${CLAUDE_ROLE_KEYS.join(" and ")} are allowed under claude`,
                    );
                else if (typeof v !== "string" || !v.trim() || /[\r\n]/.test(v))
                    errors.push(
                        `roles.${name}.${group}.${key} must be a non-empty single-line string`,
                    );
            }
        }
    }
    return errors;
}

// release block for agent-team set-version (T-46). Without it there is no error (set-version reports that itself).
// verify: commands as argument lists, versionFiles: { path, type: json|toml (key) | regex (pattern, one capture group) }.
const VERSION_FILE_TYPES = ["json", "toml", "regex"];
const isText = (v) => typeof v === "string" && v.trim() !== "";
export function releaseConfigErrors(release) {
    if (release === undefined) return [];
    if (!isObject(release))
        return ["release must be an object { verify, versionFiles, changelog, tagPrefix }"];
    const errors = [];
    const { verify, versionFiles, changelog, tagPrefix } = release;
    if (!Array.isArray(verify) || !verify.length)
        errors.push('release.verify must be a non-empty list of commands, e.g. [["npm", "test"]]');
    else
        verify.forEach((cmd, i) => {
            if (!Array.isArray(cmd) || !cmd.length || !cmd.every((a) => typeof a === "string"))
                errors.push(`release.verify[${i}] must be a non-empty list of strings`);
            else if (!isText(cmd[0])) errors.push(`release.verify[${i}]: command is missing`);
        });
    if (!Array.isArray(versionFiles) || !versionFiles.length)
        errors.push("release.versionFiles must be a non-empty list");
    else
        versionFiles.forEach((f, i) => {
            const at = `release.versionFiles[${i}]`;
            if (!isObject(f)) {
                errors.push(`${at} must be an object { path, type, key | pattern }`);
                return;
            }
            if (!isText(f.path)) errors.push(`${at}.path is missing or empty`);
            if (!VERSION_FILE_TYPES.includes(f.type))
                errors.push(`${at}.type must be ${VERSION_FILE_TYPES.join(", ")}`);
            else if (f.type === "regex") {
                if (!isText(f.pattern)) errors.push(`${at}.pattern is missing or empty`);
                else {
                    let groups = -1;
                    try {
                        groups = new RegExp(`${f.pattern}|`).exec("").length - 1;
                    } catch (e) {
                        errors.push(
                            `${at}.pattern is not a valid regular expression (${e.message})`,
                        );
                    }
                    if (groups >= 0 && groups !== 1)
                        errors.push(
                            `${at}.pattern needs exactly one capture group (found: ${groups})`,
                        );
                }
            } else if (!isText(f.key) || f.key.split(".").some((k) => !k.trim()))
                errors.push(
                    `${at}.key is missing or not a key path (e.g. version, package.version)`,
                );
        });
    if (!isText(changelog))
        errors.push("release.changelog is missing or empty (e.g. CHANGELOG.md)");
    if (typeof tagPrefix !== "string" || /\s/.test(tagPrefix))
        errors.push('release.tagPrefix must be a string without spaces (e.g. "v")');
    return errors;
}

// All config errors that sync reports with exit 2: codex block (only with "codex" in targets), then roles, then release
export function configErrors(config, roleNames) {
    const codex = (config.targets ?? ["claude"]).includes("codex")
        ? codexConfigErrors(config.codex)
        : [];
    return [
        ...codex,
        ...poolErrors(config),
        ...roleOverrideErrors(config.roles, roleNames),
        ...releaseConfigErrors(config.release),
    ];
}

// ---------- Pool placeholders in documents (T-107) ----------

// The names are built here, not written out: init and update render every template file, including this one.
const ph = (name) => `<${name}>`;

// Values of the pool placeholders from the pool sizes. The titles are the default titles of the roles
// (sync passes the titles of its roles.json entries, init and update use these defaults for AGENTS.md).
export function poolPlaceholders({
    devPool,
    criticPool,
    criticTitle = "Critic",
    devTitle = "Dev {n}",
}) {
    const chat = (role, title, pool) => ({ role, title, pool });
    return {
        [ph("CRITIC_TITLES")]: titleList(chat("critic", criticTitle, criticPool)),
        [ph("DEV_TITLES")]: titleList(chat("dev", devTitle, devPool)),
        [ph("DEV_POOL")]: String(devPool),
        // Orchestrator, critics, Advisor, Implementer, Researcher, Simplifier, devs
        [ph("CHAT_COUNT")]: String(1 + criticPool + 1 + 3 + devPool),
    };
}

const TABLE_LINE = /^\s*\|.*\|\s*$/;
const splitRow = (line) =>
    line
        .trim()
        .slice(1, -1)
        .split(/(?<!\\)\|/)
        .map((c) => c.trim());

// Aligns a markdown table the way prettier writes it (columns padded to the widest cell).
function alignTable(lines) {
    const rows = lines.map(splitRow);
    const isSep = (r) => r.every((c) => /^:?-+:?$/.test(c));
    const widths = rows[0].map((_, i) =>
        Math.max(3, ...rows.filter((r) => !isSep(r)).map((r) => [...(r[i] ?? "")].length)),
    );
    return rows.map((r) => {
        const cells = r.map((c, i) => {
            if (isSep(r)) {
                const left = c.startsWith(":");
                const right = c.endsWith(":");
                return (
                    (left ? ":" : "") + "-".repeat(widths[i] - left - right) + (right ? ":" : "")
                );
            }
            return c + " ".repeat(widths[i] - [...c].length);
        });
        return `| ${cells.join(" | ")} |`;
    });
}

// Replaces the pool placeholders. A table row that contains one is aligned again afterwards,
// so the rendered file stays as prettier writes it. Other lines are not touched.
export function renderPoolPlaceholders(text, values) {
    const keys = Object.keys(values);
    const has = (line) => keys.some((k) => line.includes(k));
    const replace = (line) => keys.reduce((l, k) => l.replaceAll(k, () => values[k]), line);
    const lines = text.split("\n");
    const out = [];
    for (let i = 0; i < lines.length; ) {
        if (!TABLE_LINE.test(lines[i])) {
            out.push(replace(lines[i++]));
            continue;
        }
        let j = i;
        while (j < lines.length && TABLE_LINE.test(lines[j])) j++;
        const block = lines.slice(i, j);
        out.push(...(block.some(has) ? alignTable(block.map(replace)) : block));
        i = j;
    }
    return out.join("\n");
}

// ---------- Project block and manifest hash (init, update and sync) ----------

export const BLOCK_START = "<!-- agent-team:project -->";
export const BLOCK_END = "<!-- /agent-team:project -->";

// Splits text at the project block. null if the block is missing or does not occur exactly once.
// before ends with BLOCK_START, after starts with BLOCK_END.
export function splitBlock(text) {
    const t = toLf(text);
    const start = t.indexOf(BLOCK_START);
    const end = t.indexOf(BLOCK_END);
    if (start < 0 || end < start) return null;
    if (t.indexOf(BLOCK_START, start + 1) >= 0 || t.indexOf(BLOCK_END, end + 1) >= 0) return null;
    const cut = start + BLOCK_START.length;
    return { before: t.slice(0, cut), block: t.slice(cut, end), after: t.slice(end) };
}

// Hash for the manifest: LF-normalised, block content removed (if there is a block)
export function hashOf(text) {
    const parts = splitBlock(text);
    const t = parts ? parts.before + parts.after : toLf(text);
    return crypto.createHash("sha256").update(t, "utf8").digest("hex");
}

// ---------- Pool texts in package-owned files (F-107-10) ----------

// init and update render AGENTS.md and team/TEAM-BEITRETEN.txt from the package with the pool values.
// sync has no package, so it finds the rendered pool texts by their fixed wording and writes the current
// values: the team table rows whose first cell is the dev or critic title list, the sentence about the
// external critic chats, and the chat count of the join text. Everything else stays as it is, the
// project block of AGENTS.md byte for byte. A text that is not found (edited by the project) is left
// alone and reported as missing.
const CRITIC_LIST = "Critic(?:, Critic \\d+)*";
const DEV_LIST = "Dev \\d+(?: … Dev \\d+|(?:, Dev \\d+)*)";
const firstCell = (list) => new RegExp(`^\\|\\s*(${list})\\s*\\|`);

export const POOL_TEXTS = {
    "AGENTS.md": [
        { name: "dev row of the team table", row: firstCell(DEV_LIST), key: "DEV_TITLES" },
        { name: "critic row of the team table", row: firstCell(CRITIC_LIST), key: "CRITIC_TITLES" },
        {
            name: "sentence about the external critic chats",
            re: new RegExp(
                `(\\*\\*The critic chats \\()(${CRITIC_LIST})(\\) and Advisor are external:\\*\\*)`,
            ),
            key: "CRITIC_TITLES",
        },
    ],
    "team/TEAM-BEITRETEN.txt": [
        { name: "chat count", re: /(The team has )(\d+)( chats:)/, key: "CHAT_COUNT" },
    ],
};

// Pool texts of one part (no project block in it): { text, missing: [names] }
function rewritePart(text, rules, values) {
    const lines = text.split("\n");
    const found = new Set();
    for (const rule of rules.filter((r) => r.re)) {
        lines.forEach((line, i) => {
            if (!rule.re.test(line)) return;
            found.add(rule.name);
            lines[i] = line.replace(rule.re, (_, a, _old, b) => a + values[ph(rule.key)] + b);
        });
    }
    const rowRules = rules.filter((r) => r.row);
    const out = [];
    for (let i = 0; i < lines.length; ) {
        if (!TABLE_LINE.test(lines[i])) {
            out.push(lines[i++]);
            continue;
        }
        let j = i;
        while (j < lines.length && TABLE_LINE.test(lines[j])) j++;
        let block = lines.slice(i, j);
        let changed = false;
        block = block.map((line) => {
            const rule = rowRules.find((r) => r.row.test(line));
            if (!rule) return line;
            found.add(rule.name);
            const cells = splitRow(line);
            const want = values[ph(rule.key)];
            if (cells[0] === want) return line;
            changed = true;
            cells[0] = want;
            return `| ${cells.join(" | ")} |`;
        });
        out.push(...(changed ? alignTable(block) : block));
        i = j;
    }
    return { text: out.join("\n"), missing: rules.map((r) => r.name).filter((n) => !found.has(n)) };
}

// The file with current pool texts, project block untouched: { text, missing: [names] }.
// rel must be a key of POOL_TEXTS; text is LF text.
export function rewritePoolTexts(rel, text, values) {
    const rules = POOL_TEXTS[rel];
    const parts = splitBlock(text);
    if (!parts) return rewritePart(text, rules, values);
    // the marker lines stay in "before"/"after"; only the text around the block is rewritten
    const head = rewritePart(parts.before, rules, values);
    const tail = rewritePart(parts.after, rules, values);
    const missing = rules
        .map((r) => r.name)
        .filter((n) => head.missing.includes(n) && tail.missing.includes(n));
    return { text: head.text + parts.block + tail.text, missing };
}

// Team panel mod (T-149): the plugin folder comes with the package (team/mod/team-panel/, agent-team update);
// sync writes the folder marketplace beside it, so the folder team/mod/ can be added once per machine
// ("+ → Plugins → Add marketplace" or /plugin marketplace add). The marketplace name carries the project
// name, so two projects on one machine do not collide. null when the plugin folder has no manifest.
export const TEAM_PANEL_PLUGIN = "team/mod/team-panel/.claude-plugin/plugin.json";
export const TEAM_PANEL_MARKETPLACE = "team/mod/.claude-plugin/marketplace.json";

export function teamPanelMarketplace(projectName, pluginJsonText) {
    if (pluginJsonText === null || pluginJsonText === undefined) return null;
    const plugin = JSON.parse(pluginJsonText);
    const slug =
        String(projectName ?? "project")
            .toLowerCase()
            .replace(/[^a-z0-9]+/g, "-")
            .replace(/^-+|-+$/g, "") || "project";
    const marketplace = {
        name: `${slug}-team`,
        owner: { name: "agent-team" },
        metadata: {
            description: "Team panel of this project. Generated by team/sync.mjs, do not edit.",
        },
        plugins: [
            {
                name: plugin.name,
                source: "./team-panel",
                description: plugin.description,
                version: plugin.version,
            },
        ],
    };
    return JSON.stringify(marketplace, null, 2) + "\n";
}
